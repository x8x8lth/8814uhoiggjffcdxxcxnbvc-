const SEARCH_FIELDS = ['name', 'fullName', 'brand', 'category', 'subcategory', 'categoryName', 'type', 'flavor', 'tasteGroup', 'volume', 'resistance', 'country', 'display', 'material', 'powerMode', 'controlType']

const buildProductIndex = (products = []) => products.map(p => {
  const nameText = normalizeText([p.name, p.fullName, p.flavor].filter(Boolean).join(' '))
  const brand = normalizeText(p.brand || '')
  const cat = normalizeText([p.category, p.subcategory, p.categoryName, p.type].filter(Boolean).join(' '))
  const text = normalizeText(SEARCH_FIELDS.map(f => p[f]).filter(v => v !== undefined && v !== null && v !== '').join(' '))
  const tokens = text.split(' ').filter(Boolean)
  return { p, nameText, nameCompact: nameText.replace(/ /g, ''), brand, cat, text, compact: text.replace(/ /g, ''), tokens, tokenSet: new Set(tokens) }
})

const scoreTerm = (prod, term) => {
  if (NUMERIC.test(term) || term.length <= 2) return prod.tokenSet.has(term) ? 3 : 0
  const compact = term.replace(/ /g, '')
  if (term.length <= 4 && !term.includes(' ')) {
    return prod.tokens.some(t => t.startsWith(term)) ? (prod.nameText.includes(term) ? 8 : 4) : 0
  }
  if (prod.nameText.includes(term) || prod.nameCompact.includes(compact)) return 10
  if (prod.brand.includes(term)) return 7
  if (prod.text.includes(term) || prod.compact.includes(compact)) return 5
  return 0
}

const scoreFuzzy = (prod, raw) => {
  if (raw.length < 4 || NUMERIC.test(raw)) return 0
  const lim = fuzzyLimit(raw.length)
  return prod.tokens.some(t => t.length >= 4 && Math.abs(t.length - raw.length) <= lim && editDistance(raw, t, lim) <= lim) ? 2 : 0
}

const scoreUnit = (prod, unit, fuzzy) => {
  let best = 0
  for (const t of unit.terms) {
    const s = scoreTerm(prod, t)
    if (s > best) best = s
    if (best >= 10) break
  }
  // збіг за категорією товару (напр. "картридж" -> категорія "Комплектуючі")
  if (unit.concepts.length && unit.concepts.some(c => c.catsNorm.some(a => prod.cat.includes(a)))) best = Math.max(best, 1.5)
  if (best === 0 && fuzzy) best = scoreFuzzy(prod, unit.raw)
  return best
}

const runPass = (index, qNorm, fuzzy) => {
  const units = buildUnits(qNorm)
  if (!units.length) return { units, scored: [] }
  const required = units.filter(u => !u.soft)
  const mustHave = required.length ? required : units
  const scored = []
  for (const prod of index) {
    let total = 0
    let ok = true
    for (const u of units) {
      const s = scoreUnit(prod, u, fuzzy)
      if (s === 0 && mustHave.includes(u)) { ok = false; break }
      total += s
    }
    if (ok) scored.push({ prod, total })
  }
  scored.sort((a, b) => b.total - a.total)
  return { units, scored }
}

// Підказка "Категорія: ..." якщо запит — це просто назва категорії/типу товару
const getHint = (units) => {
  if (!units.length) return null
  if (!units.every(u => u.concepts.length)) return null
  const c = units[0].concepts[0]
  return c ? { label: c.label, link: c.link } : null
}

const MAX_SEARCH_RESULTS = 6

const searchProducts = (index, rawQuery) => {
  const lower = rawQuery.toLowerCase()
  const swapped = swapLayout(lower)
  const variants = swapped !== lower ? [lower, swapped] : [lower]
  for (const fuzzy of [false, true]) {
    for (const v of variants) {
      const r = runPass(index, normalizeText(v), fuzzy)
      if (r.scored.length) {
        return { results: r.scored.slice(0, MAX_SEARCH_RESULTS).map(x => x.prod.p), hint: getHint(r.units) }
      }
    }
  }
  return { results: [], hint: getHint(buildUnits(normalizeText(lower))) }
}

