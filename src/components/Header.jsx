function normalizeText(value = '') {
  return String(value)
    .toLowerCase()
    .replace(/ё/g, 'е').replace(/ґ/g, 'г')
    .replace(/[іїы]/g, 'и').replace(/[єэ]/g, 'е')
    .replace(/[ʼ’'`´ъь]/g, '')
    .replace(/ω/g, 'ом')
    .replace(/(\d),(\d)/g, '$1§$2').replace(/(\d)\.(\d)/g, '$1§$2')
    .replace(/[^a-z0-9а-я§\s]/g, ' ')
    .replace(/§/g, '.')
    .replace(/(\d)([a-zа-я])/g, '$1 $2').replace(/([a-zа-я])(\d)/g, '$1 $2')
    .replace(/\s+/g, ' ')
    .trim()
}

