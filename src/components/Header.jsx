// Знаходимо групи синонімів для слова/фрази.
// Рівні точності: точний збіг -> закінчення ("картриджі") -> слово ще набирається ("картр") -> друкарська помилка
const findGroups = (phrase, multi = false) => {
  const compact = phrase.replace(/ /g, '')
  const exact = new Set()
  const ext = new Set()
  const prefix = new Set()
  for (const e of TERM_INDEX) {
    if (e.compact === compact) exact.add(e.group)
    else if (!multi) {
      const diff = compact.length - e.compact.length
      if (e.compact.length >= 4 && diff > 0 && diff <= 3 && compact.startsWith(e.compact)) ext.add(e.group)
      else if (compact.length >= 3 && e.compact.length > compact.length && e.compact.startsWith(compact)) prefix.add(e.group)
    }
  }
  if (exact.size) return [...exact]
  if (ext.size) return [...ext]
  if (prefix.size) return [...prefix]
  if (!multi && compact.length >= 4 && !/\d/.test(compact)) {
    const lim = fuzzyLimit(compact.length)
    const fuzzy = new Set()
    for (const e of TERM_INDEX) {
      if (e.compact.length >= 4 && Math.abs(e.compact.length - compact.length) <= lim && editDistance(compact, e.compact, lim) <= lim) fuzzy.add(e.group)
    }
    return [...fuzzy]
  }
  return []
}

const makeUnit = (raw, groups) => {
  const terms = new Set([raw])
  const concepts = []
  groups.forEach(g => {
    g.terms.forEach(t => terms.add(t))
    if (g.concept) concepts.push(g.concept)
  })
  return { raw, terms: [...terms], concepts, soft: groups.length > 0 && groups.every(g => g.soft) }
}

// Розбиваємо запит на "одиниці": фрази зі словника ("ельф бар") або окремі слова
const buildUnits = (qNorm) => {
  const words = qNorm.split(' ').filter(Boolean)
  const units = []
  let i = 0
  while (i < words.length) {
    let matched = false
    for (let len = Math.min(3, words.length - i); len >= 1; len--) {
      const phrase = words.slice(i, i + len).join(' ')
      const groups = findGroups(phrase, len > 1)
      if (groups.length) {
        units.push(makeUnit(phrase, groups))
        i += len
        matched = true
        break
      }
    }
    if (!matched) {
      if (!STOPWORDS.has(words[i])) units.push(makeUnit(words[i], []))
      i++
    }
  }
  return units
}

