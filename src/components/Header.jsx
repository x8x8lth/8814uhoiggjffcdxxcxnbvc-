const swapLayout = (text) => {
  const hasLat = /[a-z]/.test(text)
  const hasCyr = /[а-яіїєґыэъё]/.test(text)
  if (hasLat && !hasCyr) return text.split('').map(ch => EN_TO_UA[ch] || ch).join('')
  if (hasCyr && !hasLat) return text.split('').map(ch => UA_TO_EN[ch] || ch).join('')
  return text
}

// Відстань редагування з відсічкою та перестановкою сусідніх букв (для друкарських помилок)
const editDistance = (a, b, max) => {
  if (Math.abs(a.length - b.length) > max) return max + 1
  let prev2 = null
  let prev = Array.from({ length: b.length + 1 }, (_, j) => j)
  for (let i = 1; i <= a.length; i++) {
    const cur = [i]
    let rowMin = i
    for (let j = 1; j <= b.length; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1
      let v = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost)
      if (prev2 && i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) v = Math.min(v, prev2[j - 2] + 1)
      cur[j] = v
      if (v < rowMin) rowMin = v
    }
    if (rowMin > max) return max + 1
    prev2 = prev
    prev = cur
  }
  return prev[b.length]
}
